/**
 * Returns all countries sorted alphabetically based on user language
 */
export function getSortedCountries(lang: "ru" | "en" = "ru") {
  return [...WORLD_COUNTRIES].sort((a, b) => {
    const nameA = lang === "ru" ? a.ru : a.en;
    const nameB = lang === "ru" ? b.ru : b.en;
    return nameA.localeCompare(nameB, lang === "ru" ? "ru" : "en");
  });
}

/**
 * Finds country data by code, Russian name or English name
 */
export function findCountry(query: string): CountryData | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  return WORLD_COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === q ||
      c.ru.toLowerCase() === q ||
      c.en.toLowerCase() === q
  );
}

